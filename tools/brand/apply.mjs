#!/usr/bin/env node
// apply.mjs · push the confirmed brand into every place that uses it, so the owner changes one file (brand/brand.json)
// and one voice note (profile/VOICE.md) and the whole studio follows.
//
//   node tools/brand/apply.mjs [--dry]          # --dry: show what would change, write nothing
//
//   brand/brand.json ─┬─> brand/tokens.css                         (covers, gate images, any brand page)
//                     ├─> tools/style-reel/assets/brand.js          (mastheads, handle in the 5 video styles)
//                     ├─> tools/style-reel/assets/fonts.css + fonts (the styles' display face "Fa", from the library)
//                     └─> telegram-bot/wrangler.jsonc               (BRAND_NAME, IG_HANDLE, LANG, STORY_* colours)
//   profile/VOICE.md  ───> telegram-bot/wrangler.jsonc BRAND_VOICE  (the "## For the bot" paragraph)
// Carousels, stories, highlights, captions and previews read brand/brand.json directly. Push to deploy the bot change.
import fs from "node:fs";
import path from "node:path";
import { ROOT, loadBrand } from "../render/lib.mjs";

const dry = process.argv.includes("--dry"), changes = [];
const brand = loadBrand("brand/brand.json"), c = brand.colors;
const LIB = JSON.parse(fs.readFileSync(path.join(ROOT, "fonts/fonts.json"), "utf8"));
const rd = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
const wr = (p, s) => { const old = fs.existsSync(path.join(ROOT, p)) ? rd(p) : null; if (old === s) return; changes.push(p); if (!dry) fs.writeFileSync(path.join(ROOT, p), s); };
const fontName = (ref) => (typeof ref === "object" ? ref?.name : LIB.find((f) => f.id === ref)?.name) || null;
const rtl = ["fa", "ar"].includes(brand.lang);
const scriptFont = brand.lang === "fa" ? brand.fonts.fa || "vazirmatn" : brand.lang === "ar" ? brand.fonts.ar || "cairo" : brand.fonts.display || "inter";

// 1 · tokens.css
wr("brand/tokens.css", `/* Generated from brand/brand.json by tools/brand/apply.mjs; edit brand.json, not this file. */
:root {
  --bg: ${c.bg};
  --ink: ${c.ink};
  --accent: ${c.accent};
  --accent2: ${c.accent2};
  --muted: ${c.muted};
  --surface: ${c.surface};
  --ok: #3FB97A;
  --radius: ${brand.radius ?? 28}px;
  --font-display: "${fontName(brand.fonts.display) || "Inter"}", sans-serif;
  --font-body: "${fontName(brand.fonts.body) || "Inter"}", sans-serif;
  --font-fa: "${fontName(brand.fonts.fa || "vazirmatn")}", sans-serif;
  --font-ar: "${fontName(brand.fonts.ar || "cairo")}", sans-serif;
  --font-mono: "${fontName(brand.fonts.mono || "jetbrains-mono")}", ui-monospace, monospace;
}
`);

// 2 · style-reel brand.js
const local = brand.nameLocal || brand.name;
wr("tools/style-reel/assets/brand.js", `// Your brand, read by every style (mastheads, handles, frame labels). Generated from brand/brand.json by tools/brand/apply.mjs.
window.BRAND = {
  mast: ${JSON.stringify((brand.mast || (/[A-Za-z]/.test(brand.name) ? brand.name : (brand.handle || brand.name).replace(/^@/, ""))).toUpperCase())},      // Latin masthead (Vogue cover, HUD frame label)
  nameFa: ${JSON.stringify(local)},       // the name in the content language (Swiss frame label)
  handle: ${JSON.stringify(brand.handle || "")},    // Instagram handle
  year: ${JSON.stringify(String(new Date().getFullYear()))},             // HUD frame label
  dir: ${JSON.stringify(rtl ? "rtl" : "ltr")},
  colors: ${JSON.stringify(c)},
};
`);

// 3 · the styles' display face "Fa": copy the library font files next to the styles and alias them
if (typeof scriptFont === "string") {
  const f = LIB.find((x) => x.id === scriptFont);
  if (f) {
    const src = path.join(ROOT, path.dirname(f.css)), dst = "tools/style-reel/assets/fonts/lib";
    const css = fs.readFileSync(path.join(ROOT, f.css), "utf8").replace(/font-family:"[^"]+"/g, 'font-family:"Fa"').replace(/url\("([^"]+)"\)/g, (_, u) => `url("fonts/lib/${u}")`);
    const files = fs.readdirSync(src).filter((n) => n.endsWith(".woff2"));
    if (!dry) { fs.mkdirSync(path.join(ROOT, dst), { recursive: true }); for (const n of files) fs.copyFileSync(path.join(src, n), path.join(ROOT, dst, n)); }
    wr("tools/style-reel/assets/fonts.css", `/* "Fa" = the display face of every style, from the font library: ${f.name} (${f.license}). Generated by tools/brand/apply.mjs.
   To use your own licensed font instead, set brand.json fonts.${brand.lang === "ar" ? "ar" : brand.lang === "fa" ? "fa" : "display"} to {"name": "...", "css": "..."} and write this file by hand. */
${css.split("\n").filter((l) => l.startsWith("@font-face")).join("\n")}
`);
  }
} else changes.push("(skipped tools/style-reel/assets/fonts.css: your own font, write its @font-face as \"Fa\" by hand)");

// 4 · bot vars
const voice = fs.existsSync(path.join(ROOT, "profile/VOICE.md")) ? rd("profile/VOICE.md").match(/## For the bot[^\n]*\n+([\s\S]*?)(\n## |\n*$)/)?.[1].replace(/<!--[\s\S]*?-->/g, "").trim() : "";
const vars = { BRAND_NAME: brand.name, IG_HANDLE: brand.handle, LANG: brand.lang, STORY_BG: c.bg, STORY_INK: c.ink, STORY_ACCENT: c.accent, STORY_MUTED: c.muted };
if (voice && !/^<.*>$/.test(voice)) vars.BRAND_VOICE = voice.replace(/\s+/g, " ");
let w = rd("telegram-bot/wrangler.jsonc");
for (const [k, v] of Object.entries(vars)) {
  if (v == null || v === "") continue;
  const re = new RegExp(`("${k}":\\s*)"(?:[^"\\\\]|\\\\.)*"`);
  if (re.test(w)) w = w.replace(re, `$1${JSON.stringify(String(v))}`);
}
wr("telegram-bot/wrangler.jsonc", w);

console.log(changes.length ? `${dry ? "would change" : "changed"}:\n  ${changes.join("\n  ")}` : "everything already matches brand/brand.json");
if (!dry && changes.some((p) => p.startsWith("telegram-bot/"))) console.log("bot: run `bash telegram-bot/test/all.sh`, then commit and push to deploy.");
